//! Turns a design into files a project can use: `schema.cql` + `queries.cql` for `cqlc`, and `#[derive(CqlEntity)]`
//! structs for `cqlx`.

use crate::problem::{Problem, Table};
use crate::workload::Entity;
use std::fmt::Write as _;

fn rust_type(cql: &str) -> &'static str {
    match cql {
        "text" | "ascii" | "varchar" => "String",
        "int" => "i32",
        "bigint" | "counter" => "i64",
        "smallint" => "i16",
        "tinyint" => "i8",
        "float" => "f32",
        "double" => "f64",
        "boolean" => "bool",
        "uuid" => "uuid::Uuid",
        "timestamp" => "i64",
        "blob" => "Vec<u8>",
        _ => "String",
    }
}

fn pascal(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            p.chars()
                .next()
                .map(|c| c.to_uppercase().collect::<String>() + &p[1..])
                .unwrap_or_default()
        })
        .collect()
}

/// One `CqlEntity` struct per chosen table, named `<Entity><n>`.
pub fn cqlx_structs(p: &Problem, set: &[usize]) -> String {
    let mut out = String::from(
        "//! Generated by cqlz-gym. One entity per designed table.\n\nuse cqlx::scylla::DeserializeRow;\nuse cqlx::CqlEntity;\n\n",
    );
    for (k, &t) in set.iter().enumerate() {
        let tb: &Table = &p.tables[t];
        let e: &Entity = p.workload.entity(&tb.entity).expect("validated");
        let name = format!("{}{}", pascal(&tb.entity), k + 1);
        let table = format!("{}_{}", tb.entity, k + 1);
        let _ = writeln!(
            out,
            "#[derive(CqlEntity, DeserializeRow, Debug, Clone)]\n#[cqlx(table_name = \"{table}\")]\npub struct {name} {{"
        );
        // keys first, in key order, then the other columns
        let mut order: Vec<&String> = tb.partition.iter().collect();
        order.extend(tb.clustering.iter());
        order.extend(
            tb.columns
                .iter()
                .filter(|c| !tb.partition.contains(c) && !tb.clustering.contains(c)),
        );
        for c in order {
            let attr = e.attrs.iter().find(|a| &a.name == c).expect("validated");
            let role = if tb.partition.contains(c) {
                "    #[cqlx(partition_key)]\n".to_string()
            } else if tb.clustering.contains(c) {
                "    #[cqlx(clustering_key)]\n".to_string()
            } else {
                String::new()
            };
            let ty = rust_type(&attr.ty);
            let ty = if role.is_empty() {
                format!("Option<{ty}>")
            } else {
                ty.to_string()
            };
            let _ = writeln!(out, "{role}    pub {}: {ty},", c);
        }
        out.push_str("}\n\n");
    }
    out
}
